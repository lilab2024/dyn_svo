def signed(x, digits=3):
    return "$" + ("%." + str(digits) + "f") % x + "$"


def _note(note):
    """Note line below a table: definitions that do not belong in the short caption."""
    return [BS + "par" + BS + "smallskip", "{" + BS + "footnotesize" + BS + "emph{Note:} " + note + BS + "par}"]


def _table(env, colspec, caption, label, header, rows, sep=None, note=None, size="footnotesize"):
    lines = [BS + "begin{" + env + "}[!t]", BS + "centering", BS + size, BS + "caption{" + caption + "}",
             BS + "label{" + label + "}"]
    if sep is not None:
        lines.append(BS + "setlength{" + BS + "tabcolsep}{" + "%g" % sep + "pt}")
    lines += [BS + "begin{tabular}{" + colspec + "}", BS + "toprule"]
    lines += header + [BS + "midrule"] + [" & ".join(r) + " " + BS + BS for r in rows]
    lines += [BS + "bottomrule", BS + "end{tabular}"] + (_note(note) if note else []) + [BS + "end{" + env + "}"]
    return NL.join(lines) + NL


