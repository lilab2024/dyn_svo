def _g4_fail_kind(f):
    ratio = f["mean_speed_ratio"] < G4_SPEED_RATIO
    gap = f["max_last_gap"] > f["gap_limit"]
    rew = not f["reward_not_below_zero_av"]
    if gap and not ratio and not rew:
        return "gap"
    if gap and ratio and not rew:
        return "ratiogap"
    if gap and ratio and rew:
        return "all"
    return "other"


