def chain_macros(m, path, rel, seeds):
    rows = json.loads(Path(path).read_text(encoding="utf-8"))["summary"]
    flags = ("ok_sigma", "ok_slope", "ok_speed")
    ok = [r["exp"] for r in rows if all(r[f] for f in flags)]
    speed_only = [r["exp"] for r in rows if r["ok_sigma"] and r["ok_slope"] and not r["ok_speed"]]
    other = [r["exp"] for r in rows if r["exp"] not in ok and r["exp"] not in speed_only]
    m.add("ChainSeeds", "%d" % seeds, rel, "seeds (length)")
    m.add("ChainAdequate", join_list(ok), rel, "summary: all of ok_sigma, ok_slope, ok_speed")
    m.add("ChainSpeedOnly", join_list(speed_only), rel, "summary: only ok_speed false")
    m.add("ChainInadequate", join_list(other), rel, "summary: other failures")
    for r in rows:
        if r["exp"] in speed_only:
            m.add("ChainSpeed" + r["exp"], "%.1f" % (100 * r["speed_rel_diff"]), rel, "summary[" + r["exp"] + "].speed_rel_diff (percent)")

def exp_row(e, df, split_cfg):
    """Vehicle count and usable duration of one experiment (the same rule for dev and test rows)."""
    dur = (df["k"].max() - df["k"].min()) / float(ld.HZ) - split_cfg["segments"]["drop_first_s"]
    return {"exp": e, "regime": split_cfg["instruction_regime"][e], "vehicles": int(df["veh_id"].nunique()),
            "usable_s": float(dur)}


