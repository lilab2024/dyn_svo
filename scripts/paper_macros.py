DEV_MPC_KEYS = ("primary_v2b", "r5_v1", "primary_v5", "r5_v5", "match")
DEV_MPC_VARIANT = {"primary_v2b": "primary", "r5_v1": "r5", "primary_v5": "primary", "r5_v5": "r5"}
DEV_MATCH_SOURCE = "eval_dev_r5_v5"
DEV_MATCH_TOL = 1e-4        # the stage-2 run reproduces the dynamic log FOR of eval_dev_r5_v5 to four decimals


def _cv(doc, family):
    return {r.get("held_out"): r for r in doc.get("cross_validation", []) if r.get("family") == family}


def _finite(x):
    import math
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(x)


def dev_mpc_problems(docs, dev, matched_phi):
    """Reasons to refuse the MPC development summaries; md5 are checked in main."""
    out = [k + ": file missing" for k in DEV_MPC_KEYS if k not in docs]
    if out:
        return out
    for k, v in DEV_MPC_VARIANT.items():
        d = docs[k]
        if len(d.get("commits", [])) != 1 or d.get("any_dirty") is not False:
            out.append(k + ": commits or dirty flag")
        if d.get("variant", "primary") != v:
            out.append(k + ": variant " + str(d.get("variant")))
        for fam in ("mpc_dynamic", "mpc_fixed"):
            if sorted(_cv(d, fam)) != sorted(dev):
                out.append(k + ": " + fam + " folds differ from the dev experiments")
    for k in ("r5_v1", "r5_v5"):
        for fam in ("mpc_dynamic", "mpc_fixed"):
            for e, r in sorted(_cv(docs[k], fam).items()):
                if r.get("chosen") is None or not _finite(r.get("log_for")):
                    out.append(k + ": " + fam + " has no selection in fold " + str(e))
    mt = docs["match"]
    if mt.get("source_run") != DEV_MATCH_SOURCE or mt.get("variant") != "r5":
        out.append("match: source_run or variant")
    if mt.get("provenance", {}).get("dirty") is not False:
        out.append("match: written from a dirty tree")
    dyn = mt.get("dynamic")
    if dyn is None or dyn != docs["r5_v5"].get("final_selection", {}).get("mpc_dynamic"):
        out.append("match: dynamic configuration differs from the R5 selection")
    pe = mt.get("per_experiment", {})
    if sorted(pe) != sorted(dev):
        out.append("match: experiments differ from the dev experiments")
    else:
        ref = docs["r5_v5"].get("experiment_log_for", {})
        for e in dev:
            r = pe[e]
            x = ref.get(str(dyn) + "|" + e)
            if not _finite(x) or abs(r["log_for_dynamic"] - x) > DEV_MATCH_TOL:
                out.append("match: dynamic log FOR differs from eval_dev_r5_v5 in " + e)
            if abs(r["d_match"] - (r["log_for_dynamic"] - r["log_for_matched"])) > 1e-9:
                out.append("match: d_match inconsistent in " + e)
        ds = [pe[e]["d_match"] for e in dev]
        if not _finite(mt.get("mean_d_match")) or abs(mt["mean_d_match"] - sum(ds) / len(ds)) > 1e-9:
            out.append("match: mean_d_match inconsistent")
        if mt.get("n_negative") != sum(x < 0 for x in ds):
            out.append("match: n_negative inconsistent")
    if not _finite(mt.get("phi_match")) or abs(mt["phi_match"] - matched_phi) > 1e-9:
        out.append("match: phi_match differs from config/test_freeze.yaml")
    return out


def dev_mpc_macros(m, docs, dev, rel):
    """Exploratory MPC development numbers of Section 6; call only after dev_mpc_problems is empty."""
    import math
    m.add("DevFolds", "%d" % len(dev), rel["r5_v5"], "number of cross-validation folds (dev experiments)")
    old = _cv(docs["primary_v2b"], "mpc_dynamic")
    m.add("DevPriOldDynFolds", "%d" % sum(old[e].get("chosen") is not None for e in dev), rel["primary_v2b"],
          "folds with a selected dynamic configuration")
    new = _cv(docs["primary_v5"], "mpc_dynamic")
    chosen = [e for e in dev if new[e].get("chosen") is not None]
    m.add("DevPriNewDynFolds", "%d" % len(chosen), rel["primary_v5"], "folds with a selected dynamic configuration")
    m.add("DevPriNewDynExp", join_list(chosen), rel["primary_v5"], "held-out experiments of those folds")
    m.add("DevPriNewGOneB", pct(max([new[e]["fail_rate_g1b"] for e in chosen], default=0.0)), rel["primary_v5"],
          "largest held-out G1b failure rate of those selections (percent)")
    for tag, k, count_name, sign in (("Old", "r5_v1", "Lower", -1), ("New", "r5_v5", "Higher", 1)):
        dy, fx = _cv(docs[k], "mpc_dynamic"), _cv(docs[k], "mpc_fixed")
        d = [dy[e]["log_for"] - fx[e]["log_for"] for e in dev]
        mean = sum(d) / len(d)
        m.add("DevRfive" + tag + count_name, "%d" % sum(x * sign > 0 for x in d), rel[k],
              "folds with held-out log FOR of the dynamic selection " + count_name.lower() + " than the fixed selection")
        m.add("DevRfive" + tag + "MeanD", "%.3f" % mean, rel[k], "mean over folds of the held-out log FOR difference")
        m.add("DevRfive" + tag + "Change", pct(abs(math.exp(mean) - 1)), rel[k], "100 |exp(mean difference) - 1|")
    mt = docs["match"]
    m.add("DevMatchNeg", "%d" % mt["n_negative"], rel["match"], "n_negative")
    m.add("DevMatchMeanD", "%.3f" % mt["mean_d_match"], rel["match"], "mean_d_match")
    m.add("DevMatchRed", pct(1 - math.exp(mt["mean_d_match"])), rel["match"], "100 (1 - exp(mean_d_match))")
    m.add("DevMatchPhi", "%.2f" % (mt["phi_match"] / U16), rel["match"], "phi_match (units of pi/16)")
    m.add("DevMatchEpisodes", "%d" % mt["n_episodes_for_phi"], rel["match"], "n_episodes_for_phi")


