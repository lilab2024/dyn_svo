def data_macros(m, split_cfg, t_from):
    """Dev experiments only (the loader refuses test experiments)."""
    rows, acc = [], {"I": [], "II": []}
    for e in sp.experiments("dev"):
        df = ld.load_experiment(e)
        regime = split_cfg["instruction_regime"][e]
        rows.append(exp_row(e, df, split_cfg))
        keep = (df["t"] >= t_from) & df["follower_ok"]
        acc[regime].append(df.loc[keep, "a"].astype(float))
    import pandas as pd
    for reg in ("I", "II"):
        m.add("RealAccSd" + reg, "%.2f" % float(pd.concat(acc[reg]).std(ddof=0)), "dev data",
              "SD of recorded a, dev vehicles, t >= " + "%g" % t_from + " s, R2 applied, regime " + reg)
    veh = [r["vehicles"] for r in rows]
    m.add("DevVehMin", "%d" % min(veh), "dev data", "vehicles per dev experiment, min")
    m.add("DevVehMax", "%d" % max(veh), "dev data", "vehicles per dev experiment, max")
    return rows

def experiments_table(rows, split_cfg):
    by = {r["exp"]: r for r in rows}
    if all(e in by for e in split_cfg["experiments"]):
        cap = "ARED experiments used in this study."
        note = ("Driving regime, role (development or test), number of vehicles and usable duration after the first "
                + BS + "DropFirst~s.")
    else:
        cap = "ARED experiments used in this study. Test rows are filled at the test-freeze run."
        note = None
    lines = [BS + "begin{table}[!t]", BS + "centering", BS + "caption{" + cap + "}",
             BS + "label{tab:experiments}", BS + "begin{tabular}{lllrr}", BS + "toprule",
             "Exp. & Regime & Role & Vehicles & Usable duration (s) " + BS + BS, BS + "midrule"]
    for e in split_cfg["experiments"]:
        role = "dev" if e in split_cfg["roles"]["dev"] else "test"
        reg = split_cfg["instruction_regime"][e]
        if e in by:
            lines.append("%s & %s & %s & %d & %.0f " % (e, reg, role, by[e]["vehicles"], by[e]["usable_s"]) + BS + BS)
        else:
            lines.append("%s & %s & %s & locked & locked " % (e, reg, role) + BS + BS)
    lines += [BS + "bottomrule", BS + "end{tabular}"] + (_note(note) if note else []) + [BS + "end{table}"]
    return NL.join(lines) + NL

