def md5(path):
    return hashlib.md5(Path(path).read_bytes()).hexdigest()

def join_list(items):
    items = list(items)
    if not items:
        return "none"
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]

def tex_macro(name, value):
    return BS + "newcommand{" + BS + name + "}{" + value + "}"

class Macros:
    def __init__(self):
        self.items = []

    def add(self, name, value, source, key):
        if not name.isalpha() or any(m["name"] == name for m in self.items):
            raise ValueError("macro names must be letters only and unique: " + name)
        self.items.append({"name": name, "value": str(value), "source": source, "key": key})

    def tex(self, commit):
        head = ["% Generated by scripts/paper_macros.py at commit " + commit + "; do not edit by hand."]
        return NL.join(head + [tex_macro(m["name"], m["value"]) for m in self.items]) + NL

