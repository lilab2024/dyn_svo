def rl_problems(docs, rl, dev):
    """Every reason why the RL result files cannot be used together; empty list if consistent."""
    probs = []
    cfgs = sorted(n for n, _ in rl_configs(rl))
    for tag, variant, run in RL_VARIANTS:
        s, e = docs["eval_" + tag], docs["elig_" + tag]
        where = run + "/summary.json: "
        if len(s.get("commits", [])) != 1:
            probs.append(where + "tasks from %d commits" % len(s.get("commits", [])))
        if s.get("any_dirty") is not False:
            probs.append(where + "tasks from a dirty tree")
        if s.get("summary_provenance", {}).get("dirty") is not False:
            probs.append(where + "summary written from a dirty tree")
        if s.get("variant") != variant or s.get("variants") != [variant]:
            probs.append(where + "variant is not " + variant)
        if s.get("run_name") != run:
            probs.append(where + "run_name is not " + run)
        if s.get("train_run") != RL_TRAIN_RUN:
            probs.append(where + "train_run is not " + RL_TRAIN_RUN)
        keys = s.get("experiment_log_for", {})
        if sorted({k.split("|")[0] for k in keys} - {"hdv"}) != cfgs:
            probs.append(where + "configurations differ from config/rl.yaml")
        if sorted({k.split("|")[1] for k in keys}) != sorted(dev):
            probs.append(where + "experiments differ from the dev set")
        where = run + "/eligibility.json: "
        for key, want in (("run_name", run), ("variant", variant), ("train_run", RL_TRAIN_RUN), ("g4_run", RL_G4_RUN)):
            if e.get(key) != want:
                probs.append(where + key + " is not " + want)
        if sorted(e.get("eval_commits", [])) != sorted(s.get("commits", [])):
            probs.append(where + "eval_commits differ from the commits of the summary")
        if e.get("report_provenance", {}).get("dirty") is not False:
            probs.append(where + "report written from a dirty tree")
        if sorted(e.get("configs", {})) != cfgs:
            probs.append(where + "configurations differ from config/rl.yaml")
    g = docs["g4"]
    where = RL_G4_RUN + "/summary.json: "
    n_exp = len(cfgs) * len(rl["training_seeds"]) * len(dev)
    pc = g.get("pass_counts", {})
    if g.get("stage") != "train":
        probs.append(where + "stage is not train")
    if sorted(pc) != cfgs:
        probs.append(where + "configurations differ from config/rl.yaml")
    if g.get("n_policies") != n_exp or sum(v[1] for v in pc.values()) != n_exp:
        probs.append(where + "number of policies is not %d" % n_exp)
    if g.get("n_pass") != sum(v[0] for v in pc.values()) or len(g.get("not_passing", [])) != g.get("n_policies", 0) - g.get("n_pass", 0):
        probs.append(where + "pass counts are inconsistent")
    elif abs(g.get("pass_share_all", -1.0) - g["n_pass"] / float(max(1, g["n_policies"]))) > 1e-12:
        probs.append(where + "pass_share_all is inconsistent")
    gt = docs["gate"]
    where = "gate_rl_tune_v2/summary.json: "
    if gt.get("selected") != tune_name(rl["selected_hp"]):
        probs.append(where + "selected candidate is not " + tune_name(rl["selected_hp"]) + " ")
    if gt.get("gate_pass") is not True or gt.get("selected_pass") != gt.get("n_selected"):
        probs.append(where + "the gate did not pass")
    return probs


